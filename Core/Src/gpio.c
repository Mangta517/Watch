/**
  * @brief  EXTI 中断回调 (HAL 在 EXTI9_5_IRQHandler 上下文中调用)
  * @note   只置标志, 不在中断里做 I2C 读——坐标读取放到触摸任务/主循环里做。
  *         FreeRTOS 起来后, 可在此改为 xSemaphoreGiveFromISR(tp_sem, &xHigherPriorityTaskWoken)。
  */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  if (GPIO_Pin == TP_INT_Pin)
  {
    g_tp_int_flag = 1;
  }
}
